import { Router } from "express";
import { requireAuth } from "../middleware/auth.js";
import { requireProjectAdmin, requireProjectEditor, requireProjectMember } from "../middleware/project-auth.js";
import { engineeringController } from "../controllers/engineering-intelligence-controller.js";
import rateLimit from "express-rate-limit";
import { env } from "../config/env.js";
export const engineeringRoutes = Router({ mergeParams: true });
engineeringRoutes.use(requireAuth);
const aiLimit = rateLimit({ windowMs: env.RATE_LIMIT_WINDOW_MS, limit: 30, standardHeaders: "draft-8", legacyHeaders: false });
engineeringRoutes.post("/playground", requireProjectEditor, engineeringController.createSimulation);
engineeringRoutes.get("/playground", requireProjectMember, engineeringController.listSimulations);
engineeringRoutes.get("/playground/:simulationId", requireProjectMember, engineeringController.getSimulation);
engineeringRoutes.patch("/playground/:simulationId", requireProjectEditor, engineeringController.updateSimulation);
engineeringRoutes.post("/playground/:simulationId/simulate", requireProjectEditor, engineeringController.simulate);
engineeringRoutes.post("/playground/:simulationId/apply", requireProjectEditor, engineeringController.apply);
engineeringRoutes.post("/playground/:simulationId/discard", requireProjectEditor, engineeringController.discard);
engineeringRoutes.post("/playground/:simulationId/alternative", requireProjectEditor, engineeringController.alternative);
engineeringRoutes.get("/documentation", requireProjectMember, engineeringController.documents);
engineeringRoutes.get("/documentation/staleness", requireProjectMember, engineeringController.staleness);
engineeringRoutes.post("/documentation/generate", requireProjectEditor, engineeringController.generateDocument);
engineeringRoutes.get("/documentation/:documentId", requireProjectMember, engineeringController.getDocument);
engineeringRoutes.patch("/documentation/:documentId", requireProjectEditor, engineeringController.updateDocument);
engineeringRoutes.delete("/documentation/:documentId", requireProjectAdmin, engineeringController.deleteDocument);
engineeringRoutes.post("/documentation/:documentId/regenerate", requireProjectEditor, engineeringController.regenerateDocument);
engineeringRoutes.post("/design-review", aiLimit, requireProjectMember, engineeringController.review);
engineeringRoutes.post("/story/generate", aiLimit, requireProjectEditor, engineeringController.generateStory);
engineeringRoutes.get("/story", requireProjectMember, engineeringController.story);
engineeringRoutes.get("/insights", requireProjectMember, engineeringController.insights);